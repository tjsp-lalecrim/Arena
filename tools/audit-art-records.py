"""Fail on empty art records, missing outputs or changed recorded bytes/dimensions."""
from pathlib import Path
import hashlib,json
from PIL import Image
R=Path(__file__).resolve().parents[1]
count=0
for name in ['exportacoes-m01-06.json','exportacoes-revisao-r02.json']:
 data=json.loads((R/'doc/arte'/name).read_text(encoding='utf-8-sig'))
 for key in ['masters','exports']:
  assert data[key],(name,key,'empty')
  for record in data[key]:
   p=R/record['file'];assert p.stat().st_size>0
   assert hashlib.sha256(p.read_bytes()).hexdigest()==record['sha256'],str(p)
   assert list(Image.open(p).size)==record['size'],str(p)
   count+=1
for name in ['prompts-m01-06.json','prompts-revisao-identidade-r02.json','prompt-correcao-rato-r03.json']:
 data=json.loads((R/'doc/arte'/name).read_text(encoding='utf-8-sig'));assert data
 # Schema differs between historical array and current requests wrapper.
 content=json.dumps(data,ensure_ascii=False);assert len(content)>500,name
plugins=(R/'js/plugins.js').read_bytes();assert not plugins.startswith(b'\xef\xbb\xbf')
text=plugins.decode('utf-8');assert text.startswith('// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[') or text.startswith('// Generated by RPG Maker.\r\n// Do not edit this file directly.\r\nvar $plugins =\r\n[')
records=json.loads(text[text.index('['):text.rindex(']')+1])
for p in records:assert (R/'js/plugins'/(p['name']+'.js')).is_file()
print('PASS:',count,'master/export records nonempty, SHA256 and dimensions; 3 prompt logs nonempty; canonical UTF8 plugins and referenced files.')
