// Packaging validation only; no gameplay or browser storage access.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),crypto=require('node:crypto');
if(process.env.REQUIRE_LINUX==='1')assert.equal(process.platform,'linux','CI validation must actually run on Linux');
const root=path.resolve(process.argv[2]),manifestBytes=fs.readFileSync(path.join(root,'package-manifest.json'));
const manifest=JSON.parse(manifestBytes),sha=b=>crypto.createHash('sha256').update(b).digest('hex');
assert.match(manifest.sourceCommit,/^[a-f0-9]{40}$/);
if(process.env.EXPECTED_SOURCE_SHA)assert.equal(manifest.sourceCommit,process.env.EXPECTED_SOURCE_SHA);
assert.equal(manifest.namespace,'arena:m01:save-v1');
const names=manifest.files.map(f=>f.path),allowed=new Set(names);
assert.equal(allowed.size,names.length);
const walk=dir=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>{
 const absolute=path.join(dir,e.name);assert(!fs.lstatSync(absolute).isSymbolicLink(),'Symlink prohibited');
 return e.isDirectory()?walk(absolute):[path.relative(root,absolute).split(path.sep).join('/')];
});
assert.deepEqual(walk(root).sort(),[...names,'package-manifest.json'].sort());
assert.equal(new Set(names.map(f=>f.toLowerCase())).size,names.length,'Case-insensitive path collision');
for(const file of manifest.files){
 assert(!path.posix.isAbsolute(file.path)&&!file.path.split('/').includes('..'));
 assert(/^(index\.html|fonts\/[^/]+\.(css|ttf)|js\/.+\.js|data\/[^/]+\.json|img\/.+\.png|audio\/.+\.(ogg|m4a)|movies\/.+\.(webm|mp4))$/.test(file.path),'Unexpected runtime path: '+file.path);
 assert(!/\b(service[-_]?worker|sw)\.js$/i.test(file.path),'Service worker prohibited');
 const bytes=fs.readFileSync(path.join(root,file.path));assert.equal(bytes.length,file.bytes);assert.equal(sha(bytes),file.sha256,file.path);
}
const plugins=fs.readFileSync(path.join(root,'js/plugins.js'),'utf8');
assert.match(plugins,/^\/\/ Generated by RPG Maker\.\r?\n\/\/ Do not edit this file directly\.\r?\nvar \$plugins =\r?\n\[/);
const records=JSON.parse(plugins.slice(plugins.indexOf('['),plugins.lastIndexOf(']')+1));
assert.equal(records.find(p=>p.name==='MV_WebStorageNamespace').parameters.Namespace,manifest.namespace);
for(const p of records)assert(allowed.has('js/plugins/'+p.name+'.js'),'Missing plugin: '+p.name);
function relativeFile(from,ref){
 if(ref.startsWith('data:'))return;
 assert(!/^(?:[a-z]+:|\/)/i.test(ref),'Non-relative resource: '+ref);
 const resolved=path.posix.normalize(path.posix.join(path.posix.dirname(from),ref.split(/[?#]/)[0]));
 assert(allowed.has(resolved),'Missing resource/case mismatch: '+resolved);
}
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
for(const m of html.matchAll(/(?:src|href)=["']([^"']+)["']/g))relativeFile('index.html',m[1]);
const css=fs.readFileSync(path.join(root,'fonts/gamefont.css'),'utf8');
for(const m of css.matchAll(/url\(["']?([^"')]+)["']?\)/g))relativeFile('fonts/gamefont.css',m[1]);
