const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { TextDecoder } = require('node:util');
const { chromium } = require(process.env.ARENA_PLAYWRIGHT || 'playwright');
(async () => {
    // Protect the editor's text contract separately from browser JavaScript.
    const bytes = fs.readFileSync('js/plugins.js');
    assert.notEqual(bytes.subarray(0, 3).toString('hex'), 'efbbbf');
    const source = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
    assert.deepEqual(source.split(/\r?\n/).slice(0, 4), [
        '// Generated by RPG Maker.', '// Do not edit this file directly.', 'var $plugins =', '['
    ]);
    const records = JSON.parse(source.slice(source.indexOf('[')).trim().replace(/;$/, ''));
    const context = {}; vm.runInNewContext(source, context);
    assert.deepEqual(JSON.parse(JSON.stringify(context.$plugins)), records);
    records.forEach(r => assert.ok(fs.existsSync('js/plugins/' + r.name + '.js')));
    assert.equal(records.find(r => r.name === 'Community_Basic').status, false);
    const browser = await chromium.launch({ channel: 'chrome', headless: true });
    try {
        // Disposable browser profile: never touches personal saves/localStorage.
        const context = await browser.newContext({ viewport: { width: 1100, height: 800 } });
        // Produce an actual save under the preceding plugin composition, then
        // load it with the new plugins on the same isolated origin/profile.
        const legacyPage = await context.newPage();
        const oldPlugins = JSON.parse(fs.readFileSync('tools/fixtures/plugins-before-persistence.json', 'utf8'));
        await legacyPage.route('**/js/plugins.js', route => route.fulfill({ contentType: 'application/javascript',
            body: 'var $plugins = ' + JSON.stringify(oldPlugins) + ';' }));
        await legacyPage.goto(process.env.ARENA_URL || 'http://127.0.0.1:8765/');
        await legacyPage.waitForFunction(() => window.SceneManager && SceneManager._scene instanceof Scene_Title &&
            SceneManager._scene._commandWindow && SceneManager._scene._commandWindow.isOpenAndActive());
        await legacyPage.keyboard.down('Enter'); await legacyPage.waitForTimeout(80); await legacyPage.keyboard.up('Enter');
        await legacyPage.waitForFunction(() => SceneManager._scene instanceof Scene_Map && SceneManager._scene.isActive() && !$gamePlayer.isTransferring());
        assert.equal(await legacyPage.evaluate(() => {
            if (typeof MVStateStore !== 'undefined' || $gameSystem._persistentState !== undefined) return false;
            $gameActors.actor(1).setName('Legado do laboratório');
            $gameActors.actor(1).setHp(42);
            $gameActors.actor(1).learnSkill(9);
            $gameParty.gainItem($dataItems[2], 3);
            return DataManager.saveGame(3);
        }), true);
        await legacyPage.close();
        const page = await context.newPage();
        const errors = [];
        page.on('pageerror', e => errors.push(e.message));
        page.on('response', r => { if (r.status() >= 400) errors.push(r.status() + ' ' + r.url()); });
        await page.goto(process.env.ARENA_URL || 'http://127.0.0.1:8765/');
        await page.waitForFunction(() => window.SceneManager && SceneManager._scene instanceof Scene_Title &&
            SceneManager._scene._commandWindow && SceneManager._scene._commandWindow.isOpenAndActive());
        // The legacy save makes Continue the native default selection.
        // This is the laboratory regression; newGame is covered by test-character-creation.
        await page.evaluate(() => SceneManager._scene._commandWindow.selectSymbol('arenaLab'));
        await page.keyboard.down('Enter'); await page.waitForTimeout(80); await page.keyboard.up('Enter');
        await page.waitForFunction(() => SceneManager._scene instanceof Scene_Map && SceneManager._scene.isActive() && !$gamePlayer.isTransferring());
        const checks = await page.evaluate(() => {
            var checks = [];
            function check(value, label) { if (!value) throw new Error(label); checks.push(label); }
            function equal(a, b) { return JSON.stringify(a) === JSON.stringify(b); }
            var A = ArenaPersistence;
            var initial = A.snapshot();
            check(initial.character.raceId === null && initial.quests.MQ01.stage === 0 &&
                Object.keys(initial.resources).length === 0 && $gameParty.numItems($dataItems[1]) === 0, 'new-game-empty-contract');
            $gameActors.actor(1).setName('Teste de persistência');
            A.setIdentity('breton', 'female', 'breton.female.base');
            A.setResource('vigor', 37, 100);
            check(A.recordChoice('level-2', 'vigor', 10) === 'applied' &&
                A.recordChoice('level-2', 'vigor', 10) === 'duplicate', 'progression-receipt-idempotent');
            check($gameActors.actor(1).mhp === 100 && $gameActors.actor(1).level === 1, 'no-automatic-native-progression');
            check(A.claimSource('MQ01.ruby-key') === 'inactive', 'no-early-quest-item');
            A.setQuest('MQ01', 10, { obtainKey: false }, false);
            check(A.consumeImportant('MQ01.ruby-key', 'cell-door', 'consume') === 'missing', 'missing-item-does-not-create-receipt');
            var originalMaxItems = $gameParty.maxItems;
            $gameParty.maxItems = function() { return 0; };
            check(A.claimSource('MQ01.ruby-key') === 'capacity' &&
                !A.snapshot().sources['MQ01.ruby-key'], 'capacity-failure-does-not-mark-source');
            $gameParty.maxItems = originalMaxItems;
            var originalGainItem = $gameParty.gainItem;
            $gameParty.gainItem = function(item, amount, includeEquip) {
                originalGainItem.call(this, item, amount, includeEquip);
                if (amount > 0) throw new Error('simulated-grant-failure');
            };
            var grantFailed = false;
            try { A.claimSource('MQ01.ruby-key'); } catch (_) { grantFailed = true; }
            $gameParty.gainItem = originalGainItem;
            check(grantFailed && $gameParty.numItems($dataItems[1]) === 0 &&
                !A.snapshot().sources['MQ01.ruby-key'], 'grant-exception-rolls-back-item-and-source');
            check(A.claimSource('MQ01.ruby-key') === 'granted' && A.claimSource('MQ01.ruby-key') === 'present' &&
                $gameParty.numItems($dataItems[1]) === 1, 'source-repeat-no-item-duplication');
            $gameParty.loseItem($dataItems[1], 1);
            check(A.claimSource('MQ01.ruby-key') === 'granted' && A.snapshot().sources['MQ01.ruby-key'].grants === 2,
                'explicit-recovery-only-while-required');
            A.setQuest('MQ01', 20, { obtainKey: true, openCell: false }, false);
            A.setEnemy('technical.rat-1', 'technical.area', false, true, 0);
            A.setEnemy('technical.quest-1', 'technical.area', true, true, 0);
            A.setArea('technical.area', true, 1, 0);
            A.setShortcut('slot-1', { kind: 'skill', id: 9 });
            A.setShortcut('slot-2', { kind: 'item', id: 2 });
            $gameActors.actor(1).forceChangeEquip(3, $dataArmors[2]);
            var saved = A.snapshot();
            check(!('name' in saved.character) && !('inventory' in saved) && !('armorVisual' in saved.character), 'native-and-derived-state-not-mirrored');
            check(DataManager.saveGame(1), 'native-save-custom-state');
            A.setResource('vigor', 0, 100);
            A.setShortcut('slot-1', null);
            check(A.consumeImportant('MQ01.ruby-key', 'cell-door', 'consume') === 'consumed', 'explicit-consumption');
            check(DataManager.loadGame(1), 'native-load-custom-state');
            check(equal(A.snapshot(), saved) && A.identity().name === 'Teste de persistência' &&
                $gameActors.actor(1).armors()[0].id === 2 && $gameParty.numItems($dataItems[1]) === 1, 'roundtrip-custom-and-native');
            check(A.recordChoice('level-2', 'vigor', 10) === 'duplicate', 'load-does-not-repeat-progression');
            check(A.claimSource('MQ01.ruby-key') === 'present', 'load-does-not-regrant-item');
            check(A.consumeImportant('MQ01.ruby-key', 'cell-door', 'consume') === 'consumed' &&
                A.consumeImportant('MQ01.ruby-key', 'cell-door', 'consume') === 'duplicate' &&
                A.claimSource('MQ01.ruby-key') === 'inactive' && $gameParty.numItems($dataItems[1]) === 0,
                'consumption-receipt-prevents-recovery-and-duplicates');
            check(DataManager.saveGame(1) && DataManager.loadGame(1) && A.claimSource('MQ01.ruby-key') === 'inactive' &&
                A.snapshot().enemies['technical.rat-1'].defeated && A.snapshot().enemies['technical.quest-1'].questSpecific &&
                A.snapshot().areas['technical.area'].generation === 0, 'load-no-respawn-or-consumed-key');
            DataManager.saveGame(2);
            var missingSource = JsonEx.parse(StorageManager.load(2));
            delete missingSource.system._persistentState.namespaces.arena.data.sources;
            StorageManager.save(2, JsonEx.stringify(missingSource));
            check(DataManager.loadGame(2) && A.claimSource('MQ01.ruby-key') === 'inactive' &&
                $gameParty.numItems($dataItems[1]) === 0, 'consumption-receipt-survives-missing-source-field');
            A.setQuest('MQ01', 40, { obtainKey: true, openCell: true, reachGate: true }, true);
            check(DataManager.saveGame(1) && DataManager.loadGame(1) && A.snapshot().quests.MQ01.completed &&
                A.snapshot().quests.MQ01.stage === 40 && A.snapshot().quests.MQ01.objectives.reachGate,
                'quest-stage-objectives-completion-roundtrip');
            // A real native save container, stripped only of the new optional field,
            // represents the laboratory format before these plugins existed.
            check(DataManager.saveGame(2), 'legacy-fixture-save');
            var legacy = JsonEx.parse(StorageManager.load(2));
            delete legacy.system._persistentState;
            StorageManager.save(2, JsonEx.stringify(legacy));
            check(DataManager.loadGame(2) && A.snapshot().quests.MQ01.stage === 0 &&
                A.snapshot().character.raceId === null && A.identity().name === 'Teste de persistência' &&
                $gameParty.numItems($dataItems[1]) === 0, 'legacy-save-without-root-migrates-without-awards');
            // Missing fields in an existing namespace must be additive, preserving
            // receipts rather than resetting them or guessing old quest progress.
            A.recordChoice('legacy-choice', 'vigor', 10);
            DataManager.saveGame(2);
            var partial = JsonEx.parse(StorageManager.load(2));
            delete partial.system._persistentState.namespaces.arena.data.character;
            delete partial.system._persistentState.namespaces.arena.data.quests.MQ01.receipts;
            StorageManager.save(2, JsonEx.stringify(partial));
            check(DataManager.loadGame(2) && A.snapshot().character.actorId === 1 &&
                Object.keys(A.snapshot().quests.MQ01.receipts).length === 0 &&
                A.recordChoice('legacy-choice', 'vigor', 10) === 'duplicate', 'partial-fields-preserve-operation-ledger');
            var threw = false;
            try { A.setShortcut('slot-3', { kind: 'skill', id: 9999 }); } catch (_) { threw = true; }
            check(threw && !('slot-3' in A.snapshot().hotbar), 'invalid-shortcut-rejected');
            A.setQuest('MQ01', 10, { obtainKey: false }, false);
            A.claimSource('MQ01.ruby-key');
            check(A.consumeImportant('MQ01.ruby-key', 'technical-delivery', 'deliver') === 'consumed' &&
                A.consumeImportant('MQ01.ruby-key', 'technical-delivery', 'deliver') === 'duplicate' &&
                A.snapshot().quests.MQ01.receipts['technical-delivery'].kind === 'deliver' &&
                A.claimSource('MQ01.ruby-key') === 'inactive', 'delivery-receipt-is-distinct-and-idempotent');
            check(DataManager.loadGame(3) && A.identity().name === 'Legado do laboratório' &&
                $gameActors.actor(1).hp === 42 && $gameActors.actor(1).isLearnedSkill(9) &&
                $gameParty.numItems($dataItems[2]) === 3 && A.snapshot().character.raceId === null &&
                A.snapshot().quests.MQ01.stage === 0 && $gameParty.numItems($dataItems[1]) === 0,
                'actual-previous-plugin-composition-save-loads-native-data-and-new-defaults');
            DataManager.setupNewGame();
            check(A.snapshot().character.raceId === null && Object.keys(A.snapshot().progression.choices).length === 0 &&
                $gameParty.numItems($dataItems[1]) === 0, 'second-new-game-isolated');
            return checks;
        });
        assert.deepEqual(errors, []);
        const result = { browser: await browser.version(), engine: 'MV 1.6.1', checks,
            errors, isolation: 'Disposable Chrome context; native save slots 1/2/3 only inside it.',
            legacyFixture: 'Slot 3 generated by the real preceding plugin composition (fixture from 5d10e90); slots 1/2 also cover absent/partial fields. No personal save used.',
            editor: 'Not tested this round; canonical file structure checked separately.', galaxyA56: 'Not tested' };
        fs.mkdirSync('tmp', { recursive: true });
        fs.writeFileSync('tmp/persistence-result.json', JSON.stringify(result, null, 2));
        console.log(JSON.stringify(result, null, 2));
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
